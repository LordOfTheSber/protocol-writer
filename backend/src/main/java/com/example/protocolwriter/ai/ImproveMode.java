package com.example.protocolwriter.ai;

/** Режим улучшения текста протокола. */
public enum ImproveMode {
    IMPROVE,
    SHORTEN,
    EXPAND,
    FIX_GRAMMAR;

    /**
     * Java-фича: исчерпывающий switch по enum — при добавлении нового режима
     * код не скомпилируется, пока не появится инструкция для него.
     */
    String instruction() {
        return switch (this) {
            case IMPROVE -> "Улучши стиль и ясность текста: сделай формулировки чёткими и деловыми, "
                    + "убери канцелярит и повторы, сохрани все факты, имена, даты и цифры.";
            case SHORTEN -> "Сократи текст, сохранив все ключевые факты, решения, имена, даты и цифры. "
                    + "Убери воду и второстепенные детали.";
            case EXPAND -> "Разверни текст: добавь связки и поясняющие формулировки там, где мысль "
                    + "обрывочна, но не выдумывай новых фактов, имён или цифр.";
            case FIX_GRAMMAR -> "Исправь орфографические, пунктуационные и грамматические ошибки. "
                    + "Не меняй смысл, стиль и структуру текста.";
        };
    }
}
